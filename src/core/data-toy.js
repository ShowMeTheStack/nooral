// Two-dimensional toy sets for classifiers (moons, circles, blobs, spirals, XOR, checkerboard, noisy linear) and
// one-dimensional regression curves. Every set is generated from its seed, so the same options give the same
// points; classes are balanced as evenly as n allows (the first classes take any remainder), and rows are shuffled.
(function (S) {
  'use strict';
  const D = (S.Data = S.Data || {});
  const R = (v) => D.round(v, 4);

  const finish = (pts, labels, rnd, feat, extra) => {
    const idx = rnd.shuffle(pts.map((_, i) => i));
    const X = idx.map((i) => pts[i].map(R)), y = idx.map((i) => labels[i]);
    return D.table(X, y, feat || [{ name: 'x1', type: 'number' }, { name: 'x2', type: 'number' }], { name: 'class', type: 'category' }, extra);
  };
  const toyDoc = (title, story, rule, nDefault, classes, extra) => Object.assign({
    title, kind: 'toy', story, rule, source: 'Generated by Nooral from a seed', licence: 'GPL-3.0-or-later (part of Nooral)',
    size: nDefault + ' points by default (any n)', features: ['x1', 'x2'], target: 'class: ' + classes.join(', '),
    balance: 'as even as n allows across ' + classes.length + ' classes', classes,
  }, extra || {});

  /** two interleaving half circles */
  D.moons = (opt = {}) => {
    const n = opt.n || 200, noise = opt.noise == null ? 0.1 : opt.noise, rnd = D.rng(opt.seed || 1), [a, b] = D.even(n, 2), pts = [], ys = [];
    for (let i = 0; i < a; i++) { const t = a > 1 ? (Math.PI * i) / (a - 1) : 0; pts.push([Math.cos(t), Math.sin(t)]); ys.push(0); }
    for (let i = 0; i < b; i++) { const t = b > 1 ? (Math.PI * i) / (b - 1) : 0; pts.push([1 - Math.cos(t), 0.5 - Math.sin(t)]); ys.push(1); }
    pts.forEach((p) => { p[0] += rnd.normal(0, noise); p[1] += rnd.normal(0, noise); });
    return finish(pts, ys, rnd);
  };
  D.register('moons', toyDoc('Two moons', 'Two crescents that hook into each other: no straight line separates them.', 'Class 0 lies on the upper half circle (cos t, sin t), class 1 on the shifted lower one (1 − cos t, 0.5 − sin t), t evenly spaced in [0, π], plus Gaussian noise (default 0.1).', 200, [0, 1]), D.moons);

  /** a ring around a disc */
  D.circles = (opt = {}) => {
    const n = opt.n || 200, noise = opt.noise == null ? 0.08 : opt.noise, factor = opt.factor || 0.5, rnd = D.rng(opt.seed || 1), [a, b] = D.even(n, 2), pts = [], ys = [];
    for (let i = 0; i < a; i++) { const t = (2 * Math.PI * i) / a; pts.push([Math.cos(t), Math.sin(t)]); ys.push(0); }
    for (let i = 0; i < b; i++) { const t = (2 * Math.PI * i) / b; pts.push([factor * Math.cos(t), factor * Math.sin(t)]); ys.push(1); }
    pts.forEach((p) => { p[0] += rnd.normal(0, noise); p[1] += rnd.normal(0, noise); });
    return finish(pts, ys, rnd);
  };
  D.register('circles', toyDoc('Circles', 'A ring of one class around a disc of the other: a boundary must curve all the way round.', 'Class 0 evenly spaced on the unit circle, class 1 on a circle of radius factor (default 0.5), plus Gaussian noise (default 0.08).', 200, [0, 1]), D.circles);

  /** Gaussian blobs around k centres */
  D.blobs = (opt = {}) => {
    const n = opt.n || 300, k = opt.centers ? opt.centers.length : opt.k || 3, sd = opt.std || 0.8, rnd = D.rng(opt.seed || 1);
    const centers = opt.centers || Array.from({ length: k }, () => [rnd.range(-6, 6), rnd.range(-6, 6)]);
    const pts = [], ys = [];
    D.even(n, k).forEach((m, c) => { for (let i = 0; i < m; i++) { pts.push([centers[c][0] + rnd.normal(0, sd), centers[c][1] + rnd.normal(0, sd)]); ys.push(c); } });
    return finish(pts, ys, rnd, null, { centers: centers.map((c) => c.map(R)) });
  };
  D.register('blobs', toyDoc('Blobs', 'Round clouds of points around a few centres: the friendliest set for clustering and for nearest neighbours.', 'k centres (default 3) uniform in [−6, 6]², each point a centre plus Gaussian noise with standard deviation std (default 0.8).', 300, [0, 1, 2], { classesNote: 'k classes' }), D.blobs);

  /** k interleaved spiral arms */
  D.spirals = (opt = {}) => {
    const n = opt.n || 300, k = opt.k || 2, turns = opt.turns || 1.5, noise = opt.noise == null ? 0.05 : opt.noise, rnd = D.rng(opt.seed || 1), pts = [], ys = [];
    D.even(n, k).forEach((m, c) => { for (let i = 0; i < m; i++) { const r = (i + 1) / m, a = 2 * Math.PI * (turns * r + c / k); pts.push([r * Math.cos(a) + rnd.normal(0, noise), r * Math.sin(a) + rnd.normal(0, noise)]); ys.push(c); } });
    return finish(pts, ys, rnd);
  };
  D.register('spirals', toyDoc('Spirals', 'Arms that wind around the centre: a hard test of whether a model can bend its boundary many times.', 'Arm c of k (default 2): radius r from 1/m to 1, angle 2π(turns·r + c/k) with turns = 1.5, plus Gaussian noise (default 0.05).', 300, [0, 1]), D.spirals);

  /** the four quadrants, opposite corners sharing a class */
  D.xor = (opt = {}) => {
    const n = opt.n || 200, noise = opt.noise == null ? 0.0 : opt.noise, rnd = D.rng(opt.seed || 1), pts = [], ys = [];
    const quads = [[1, 1, 0], [-1, -1, 0], [-1, 1, 1], [1, -1, 1]];
    D.even(n, 4).forEach((m, q) => { for (let i = 0; i < m; i++) { const [sx, sy, c] = quads[q]; pts.push([sx * rnd.range(0.05, 1), sy * rnd.range(0.05, 1)]); ys.push(rnd() < noise ? 1 - c : c); } });
    return finish(pts, ys, rnd);
  };
  D.register('xor', toyDoc('XOR', 'Opposite corners belong together: the classic set that a single straight line cannot solve.', 'Points uniform in each quadrant (|x| from 0.05 to 1), class 0 where x1·x2 > 0 and class 1 where x1·x2 < 0; a fraction noise (default 0) of labels flipped.', 200, [0, 1], { balance: 'exactly even when n is a multiple of 4 (before label noise)' }), D.xor);

  /** a checkerboard of cells */
  D.checkerboard = (opt = {}) => {
    const n = opt.n || 400, cells = opt.cells || 4, rnd = D.rng(opt.seed || 1), pts = [], ys = [];
    const [a, b] = D.even(n, 2), need = [a, b];
    while (need[0] + need[1] > 0) { const p = [rnd.range(0, cells), rnd.range(0, cells)], c = (Math.floor(p[0]) + Math.floor(p[1])) % 2; if (need[c] > 0) { need[c]--; pts.push(p); ys.push(c); } }
    return finish(pts, ys, rnd);
  };
  D.register('checkerboard', toyDoc('Checkerboard', 'Alternating squares: every cell flips the class, so a model needs many small regions.', 'Points uniform in [0, cells)² (cells = 4); the class is (⌊x1⌋ + ⌊x2⌋) mod 2; points are drawn until each class has its share.', 400, [0, 1]), D.checkerboard);

  /** two classes split by a line, with some labels flipped */
  D.linear = (opt = {}) => {
    const n = opt.n || 200, noise = opt.noise == null ? 0.05 : opt.noise, rnd = D.rng(opt.seed || 1), w = opt.w || [1, -0.6], b = opt.b == null ? 0.2 : opt.b, pts = [], ys = [];
    const [a, c] = D.even(n, 2), need = [a, c];
    while (need[0] + need[1] > 0) { const p = [rnd.range(-2, 2), rnd.range(-2, 2)], k = w[0] * p[0] + w[1] * p[1] + b > 0 ? 1 : 0; if (need[k] > 0) { need[k]--; pts.push(p); ys.push(rnd() < noise ? 1 - k : k); } }
    return finish(pts, ys, rnd, null, { w, b });
  };
  D.register('linear', toyDoc('Noisy line', 'Two classes on either side of a straight line, with a few labels flipped: what a linear model is made for.', 'Points uniform in [−2, 2]²; class 1 where x1 − 0.6·x2 + 0.2 > 0, drawn until each side has its share; then a fraction noise (default 0.05) of labels flipped.', 200, [0, 1], { balance: 'even before label noise' }), D.linear);

  const SHAPES = {
    sine: (x) => Math.sin(x), poly: (x) => 0.1 * x * x * x - 0.5 * x, step: (x) => (x < -1 ? -1 : x < 1 ? 0.5 : 1.5), linear: (x) => 0.8 * x + 0.5, abs: (x) => Math.abs(x) - 1,
  };
  /** y = shape(x) + noise for x uniform in [−3, 3]; shapes: sine, poly, step, linear, abs */
  D.curve = (opt = {}) => {
    const n = opt.n || 100, shape = opt.shape || 'sine', noise = opt.noise == null ? 0.15 : opt.noise, rnd = D.rng(opt.seed || 1), g = SHAPES[shape];
    if (!g) throw new Error('unknown curve shape ' + shape);
    const xs = Array.from({ length: n }, () => rnd.range(-3, 3)).sort((a, b) => a - b);
    return D.table(xs.map((x) => [R(x)]), xs.map((x) => R(g(x) + rnd.normal(0, noise))), [{ name: 'x', type: 'number' }], { name: 'y', type: 'number' }, { truth: g, shape });
  };
  D.register('curve', { title: 'Regression curves', kind: 'toy', story: 'One input and one noisy output along a known curve, for fitting lines, polynomials, trees and networks and seeing over- and under-fitting.', rule: 'x uniform in [−3, 3], sorted; y = shape(x) + Gaussian noise (default 0.15). Shapes: sine sin x; poly 0.1x³ − 0.5x; step −1 / 0.5 / 1.5 with steps at x = −1 and 1; linear 0.8x + 0.5; abs |x| − 1.', source: 'Generated by Nooral from a seed', licence: 'GPL-3.0-or-later (part of Nooral)', size: '100 points by default', features: ['x'], target: 'y (number)', balance: 'not a classification set' }, D.curve);
  D.curveShapes = Object.keys(SHAPES);
})(globalThis.Nooral = globalThis.Nooral || {});
